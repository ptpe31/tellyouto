const leaves = JSON.parse(
  fs.readFileSync(path.join(__dirname, 'en-leaves.json'), 'utf8'),
);

const langs = { ja, zh, ar, ko, nl, sv };
const outDir = path.join(__dirname, 'locale-data');
fs.mkdirSync(outDir, { recursive: true });

for (const [lang, values] of Object.entries(langs)) {
  if (values.length !== leaves.length) {
    throw new Error(`${lang}: expected ${leaves.length} entries, got ${values.length}`);
  }
  const obj = {};
  for (let i = 0; i < leaves.length; i++) {
    obj[leaves[i][0]] = values[i];
  }
  const outPath = path.join(outDir, `${lang}.json`);
  fs.writeFileSync(outPath, JSON.stringify(obj, null, 2) + '\n', 'utf8');
  console.log(`${lang}.json: ${Object.keys(obj).length} keys → ${outPath}`);
}
